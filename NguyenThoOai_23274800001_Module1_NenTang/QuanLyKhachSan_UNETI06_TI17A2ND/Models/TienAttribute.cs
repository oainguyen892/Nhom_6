using System.ComponentModel.DataAnnotations;
using Microsoft.AspNetCore.Mvc.ModelBinding.Validation;
namespace QuanLyKhachSan_UNETI06_TI17A2ND.Models;

public sealed class TienAttribute : ValidationAttribute, IClientModelValidator
{
    public TienAttribute() : base("Đơn giá chỉ được có tối đa hai chữ số thập phân.") { }
    public override bool IsValid(object? value) => value is decimal n && decimal.Round(n, 2) == n;
    public void AddValidation(ClientModelValidationContext context)
    {
        context.Attributes.TryAdd("data-val", "true");
        context.Attributes.TryAdd("data-val-tien", ErrorMessageString);
    }
}
